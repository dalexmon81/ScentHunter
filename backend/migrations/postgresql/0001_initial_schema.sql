-- ScentHunter PostgreSQL foundation, migration 0001.
-- This creates the target schema only. It does not import data or switch production
-- traffic away from the existing SQLite catalog.
BEGIN;

CREATE TABLE IF NOT EXISTS schema_migrations (
    version BIGINT PRIMARY KEY,
    name TEXT NOT NULL,
    applied_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS retailers (
    code TEXT PRIMARY KEY,
    display_name TEXT NOT NULL,
    base_url TEXT NOT NULL,
    is_active BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

-- Canonical identity is independent from retailer listings and prices.
CREATE TABLE IF NOT EXISTS canonical_products (
    product_id TEXT PRIMARY KEY,
    brand_name TEXT NOT NULL,
    canonical_name TEXT NOT NULL,
    concentration TEXT,
    canonical_image_url TEXT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS canonical_product_aliases (
    product_id TEXT NOT NULL REFERENCES canonical_products(product_id) ON DELETE CASCADE,
    alias TEXT NOT NULL,
    PRIMARY KEY (product_id, alias)
);

CREATE TABLE IF NOT EXISTS canonical_variants (
    variant_id TEXT PRIMARY KEY,
    product_id TEXT NOT NULL REFERENCES canonical_products(product_id) ON DELETE CASCADE,
    size_ml NUMERIC(10, 2) CHECK (size_ml IS NULL OR size_ml > 0),
    label TEXT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS idx_canonical_variants_product
    ON canonical_variants(product_id);

CREATE TABLE IF NOT EXISTS canonical_variant_aliases (
    variant_id TEXT NOT NULL REFERENCES canonical_variants(variant_id) ON DELETE CASCADE,
    alias TEXT NOT NULL,
    PRIMARY KEY (variant_id, alias)
);

-- One retailer product page is the stable discovery/hydration unit.
CREATE TABLE IF NOT EXISTS retailer_products (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    retailer_code TEXT NOT NULL REFERENCES retailers(code),
    product_url TEXT NOT NULL,
    slug TEXT NOT NULL DEFAULT '',
    last_modified TEXT,
    discovered_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    is_active BOOLEAN NOT NULL DEFAULT TRUE,
    UNIQUE (retailer_code, product_url),
    UNIQUE (id, retailer_code, product_url)
);

CREATE INDEX IF NOT EXISTS idx_retailer_products_slug
    ON retailer_products(retailer_code, slug);
CREATE INDEX IF NOT EXISTS idx_retailer_products_active
    ON retailer_products(retailer_code, is_active);

-- Current hydrated data for the retailer page. Canonical matching remains
-- nullable and is only populated after an explicit MATCHED decision.
CREATE TABLE IF NOT EXISTS retailer_offers (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    retailer_product_id BIGINT NOT NULL UNIQUE
        REFERENCES retailer_products(id) ON DELETE CASCADE,
    raw_name TEXT,
    brand_raw TEXT,
    image_url TEXT,
    sku TEXT,
    gtin TEXT,
    mpn TEXT,
    size_ml NUMERIC(10, 2) CHECK (size_ml IS NULL OR size_ml > 0),
    concentration TEXT,
    gender TEXT,
    price NUMERIC(12, 4) CHECK (price IS NULL OR price >= 0),
    currency CHAR(3) NOT NULL DEFAULT 'EUR',
    availability TEXT,
    fetched_at TIMESTAMPTZ,
    fetch_status TEXT,
    canonical_product_id TEXT REFERENCES canonical_products(product_id),
    canonical_variant_id TEXT REFERENCES canonical_variants(variant_id),
    match_status TEXT NOT NULL DEFAULT 'unresolved'
        CHECK (match_status IN ('matched', 'unresolved', 'ambiguous')),
    match_confidence NUMERIC(5, 4)
        CHECK (match_confidence IS NULL OR match_confidence BETWEEN 0 AND 1),
    CHECK (
        (match_status = 'matched'
            AND canonical_product_id IS NOT NULL
            AND canonical_variant_id IS NOT NULL)
        OR
        (match_status <> 'matched'
            AND canonical_product_id IS NULL
            AND canonical_variant_id IS NULL)
    ),
    CHECK (char_length(trim(currency)) = 3)
);

CREATE INDEX IF NOT EXISTS idx_retailer_offers_price
    ON retailer_offers(price) WHERE price IS NOT NULL AND price > 0;
CREATE INDEX IF NOT EXISTS idx_retailer_offers_canonical
    ON retailer_offers(canonical_product_id, canonical_variant_id);
CREATE INDEX IF NOT EXISTS idx_retailer_offers_fetched
    ON retailer_offers(fetched_at);

-- Multiple bottle sizes can be listed on one retailer product page.
CREATE TABLE IF NOT EXISTS retailer_offer_variants (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    retailer_product_id BIGINT NOT NULL
        REFERENCES retailer_products(id) ON DELETE CASCADE,
    variant_key TEXT NOT NULL,
    raw_name TEXT,
    brand_raw TEXT,
    image_url TEXT,
    sku TEXT,
    gtin TEXT,
    mpn TEXT,
    size_ml NUMERIC(10, 2) CHECK (size_ml IS NULL OR size_ml > 0),
    concentration TEXT,
    gender TEXT,
    price NUMERIC(12, 4) CHECK (price IS NULL OR price >= 0),
    currency CHAR(3) NOT NULL DEFAULT 'EUR',
    availability TEXT,
    fetched_at TIMESTAMPTZ,
    variant_url TEXT,
    UNIQUE (retailer_product_id, variant_key),
    CHECK (price IS NULL OR price >= 0),
    CHECK (char_length(trim(currency)) = 3)
);

CREATE INDEX IF NOT EXISTS idx_retailer_offer_variants_parent
    ON retailer_offer_variants(retailer_product_id);
CREATE INDEX IF NOT EXISTS idx_retailer_offer_variants_size
    ON retailer_offer_variants(size_ml);

CREATE TABLE IF NOT EXISTS retailer_sync_state (
    retailer_code TEXT PRIMARY KEY REFERENCES retailers(code),
    status TEXT,
    started_at TIMESTAMPTZ,
    finished_at TIMESTAMPTZ,
    discovered_count BIGINT NOT NULL DEFAULT 0 CHECK (discovered_count >= 0),
    fetched_count BIGINT NOT NULL DEFAULT 0 CHECK (fetched_count >= 0),
    last_error TEXT
);

-- Discovery queue stores navigation/catalog pages, not product hydration work.
CREATE TABLE IF NOT EXISTS catalog_discovery_queue (
    retailer_code TEXT NOT NULL REFERENCES retailers(code),
    url TEXT NOT NULL,
    depth INTEGER NOT NULL DEFAULT 0 CHECK (depth >= 0),
    priority INTEGER NOT NULL DEFAULT 100,
    source TEXT NOT NULL DEFAULT '',
    state TEXT NOT NULL DEFAULT 'PENDING',
    attempts INTEGER NOT NULL DEFAULT 0 CHECK (attempts >= 0),
    available_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    leased_until TIMESTAMPTZ,
    lease_token TEXT,
    first_seen_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    last_started_at TIMESTAMPTZ,
    last_finished_at TIMESTAMPTZ,
    last_error TEXT,
    PRIMARY KEY (retailer_code, url)
);

CREATE INDEX IF NOT EXISTS idx_discovery_queue_ready
    ON catalog_discovery_queue(retailer_code, state, available_at, priority, depth);

CREATE TABLE IF NOT EXISTS hydration_queue (
    retailer_code TEXT NOT NULL,
    product_url TEXT NOT NULL,
    state TEXT NOT NULL DEFAULT 'PENDING',
    priority INTEGER NOT NULL DEFAULT 100,
    attempts INTEGER NOT NULL DEFAULT 0 CHECK (attempts >= 0),
    available_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    leased_until TIMESTAMPTZ,
    lease_token TEXT,
    first_seen_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    last_started_at TIMESTAMPTZ,
    last_finished_at TIMESTAMPTZ,
    last_error TEXT,
    last_http_status INTEGER,
    PRIMARY KEY (retailer_code, product_url),
    FOREIGN KEY (retailer_code, product_url)
        REFERENCES retailer_products(retailer_code, product_url) ON DELETE CASCADE
);

CREATE INDEX IF NOT EXISTS idx_hydration_queue_ready
    ON hydration_queue(retailer_code, state, priority, attempts, available_at, first_seen_at);
CREATE INDEX IF NOT EXISTS idx_hydration_queue_lease
    ON hydration_queue(state, leased_until);

CREATE TABLE IF NOT EXISTS hydration_scheduler (
    singleton_id SMALLINT PRIMARY KEY DEFAULT 1 CHECK (singleton_id = 1),
    last_retailer_index INTEGER NOT NULL DEFAULT 0 CHECK (last_retailer_index >= 0)
);

INSERT INTO hydration_scheduler(singleton_id, last_retailer_index)
VALUES (1, 0) ON CONFLICT (singleton_id) DO NOTHING;

CREATE TABLE IF NOT EXISTS catalog_coverage (
    retailer_code TEXT NOT NULL REFERENCES retailers(code),
    product_id TEXT NOT NULL REFERENCES canonical_products(product_id),
    canonical_name TEXT NOT NULL,
    query TEXT NOT NULL,
    state TEXT NOT NULL DEFAULT 'PENDING',
    attempts INTEGER NOT NULL DEFAULT 0 CHECK (attempts >= 0),
    found_urls INTEGER NOT NULL DEFAULT 0 CHECK (found_urls >= 0),
    last_started_at TIMESTAMPTZ,
    last_finished_at TIMESTAMPTZ,
    next_run_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    last_error TEXT,
    PRIMARY KEY (retailer_code, product_id)
);

CREATE INDEX IF NOT EXISTS idx_catalog_coverage_ready
    ON catalog_coverage(state, next_run_at, retailer_code);
CREATE INDEX IF NOT EXISTS idx_catalog_coverage_product
    ON catalog_coverage(product_id, state);

INSERT INTO schema_migrations(version, name)
VALUES (1, 'initial_catalog_schema')
ON CONFLICT (version) DO NOTHING;

COMMIT;
